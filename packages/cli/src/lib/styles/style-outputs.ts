/**
 * @file
 * Generated `.canvas/` style outputs and Tailwind candidates.
 *
 * `.canvas/` is meant to be committed, like a lockfile:
 * - `styles.json`: a snapshot of the style definitions the site offers.
 * - `styles.d.ts`: `CanvasStyleRegistry` augmentation, so
 *   `useStyleOptions()` is typed per component from its `component.yml`.
 * - `styles.css`: `@source inline()` with every option class, for front ends
 *   that build Tailwind themselves.
 */

import fs from 'fs/promises';
import path from 'path';

import type {
  StyleCustom,
  StyleCustomRange,
  StyleDefinition,
} from '@drupal-canvas/ui/types/Styles';
import type { Component } from '../../types/Component';
import type { StyleLibraryPayload } from './style-library';

export const CANVAS_OUTPUT_DIR = '.canvas';
export const STYLES_SNAPSHOT_FILENAME = 'styles.json';

/** The parts of a style definition the CLI reads. */
export type StyleDefinitionSummary = Pick<StyleDefinition, 'id'> &
  Partial<Omit<StyleDefinition, 'id' | 'options'>> & {
    options: Array<
      Pick<StyleDefinition['options'][number], 'id' | 'value' | 'attribute'> &
        Partial<StyleDefinition['options'][number]>
    >;
  };

/** What a component accepts: `'*'`, a list of style IDs, or nothing. */
export type AcceptedStyles = '*' | string[] | undefined;

/** Named parts as component.yml or the API expresses them. */
export type StyleParts = NonNullable<Component['styleParts']>;

/** The style IDs a part accepts, from a list or a map of limits. */
export function partStyleIds(part: StyleParts[string]): string[] {
  return Array.isArray(part.styles) ? part.styles : Object.keys(part.styles);
}

/**
 * Converts parts as the API stores them (`styles` list plus `limits`) to the
 * authored component.yml shape: a list, or a map of style ID to a limit when
 * any style has one.
 */
export function authoredStyleParts(parts: StyleParts): StyleParts {
  return Object.fromEntries(
    Object.entries(parts).map(([id, part]) => {
      const styles = partStyleIds(part);
      const limits = part.limits ?? {};
      return [
        id,
        {
          label: part.label,
          styles:
            Array.isArray(part.styles) && Object.keys(limits).length > 0
              ? Object.fromEntries(
                  styles.map((style) => [style, limits[style] ?? null]),
                )
              : part.styles,
        },
      ];
    }),
  );
}

const CODE_COMPONENT_ATTRIBUTES = ['class', 'style'];
const CUSTOM_PROPERTY_PATTERN = /^--[a-z0-9-]+$/;
const CUSTOM_UNIT_PATTERN = /^[a-z%]+$/;
const GENERATED_HEADER =
  'Generated by `canvas pull` from component.yml files and the site styles. Do not edit.';

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}

/**
 * Normalizes an authored `custom` declaration to the shape the API serves,
 * or null when it has no class or a valid custom property.
 *
 * @see \Drupal\canvas\Style\StyleValues::normalizeCustom()
 */
export function normalizeStyleCustom(custom: unknown): StyleCustom | null {
  if (!isRecord(custom)) {
    return null;
  }
  const value = typeof custom.value === 'string' ? custom.value.trim() : '';
  const property = typeof custom.property === 'string' ? custom.property : '';
  if (value === '' || !CUSTOM_PROPERTY_PATTERN.test(property)) {
    return null;
  }
  const number = (n: unknown): number | null =>
    typeof n === 'number' && Number.isFinite(n) ? n : null;
  const bounds = (b: unknown): StyleCustomRange => ({
    min: number(isRecord(b) ? b.min : null),
    max: number(isRecord(b) ? b.max : null),
    step: number(isRecord(b) ? b.step : null),
  });
  const ranges: Record<string, StyleCustomRange> = {};
  const units = custom.units;
  if (Array.isArray(units) ? units.length > 0 : isRecord(units)) {
    // A plain list of units has no bounds.
    const entries: [string, unknown][] = Array.isArray(units)
      ? units.map((unit) => [String(unit), null])
      : Object.entries(units as Record<string, unknown>);
    for (const [unit, unitBounds] of entries) {
      if (CUSTOM_UNIT_PATTERN.test(unit)) {
        ranges[unit] = bounds(unitBounds);
      }
    }
    if (Object.keys(ranges).length === 0) {
      return null;
    }
  } else {
    ranges[''] = bounds(custom);
  }
  const unitList = Object.keys(ranges);
  const unitless = unitList.length === 1 && unitList[0] === '';
  const type: StyleCustom['type'] = unitless
    ? custom.type === 'integer'
      ? 'integer'
      : 'number'
    : unitList.length === 1 && unitList[0] === '%'
      ? 'percentage'
      : 'length';
  return {
    type,
    units: unitList,
    ...ranges[unitList[0]],
    ranges,
    value,
    property,
  };
}

function normalizeStyleTokens(
  tokens: unknown,
): StyleDefinition['tokens'] | null {
  if (
    !isRecord(tokens) ||
    typeof tokens.value !== 'string' ||
    tokens.value.trim() === '' ||
    typeof tokens.property !== 'string'
  ) {
    return null;
  }
  return {
    type: typeof tokens.type === 'string' ? tokens.type : 'color',
    folders: Array.isArray(tokens.folders)
      ? tokens.folders.filter((f): f is string => typeof f === 'string')
      : [],
    value: tokens.value.trim(),
    property: tokens.property,
  };
}

/**
 * Converts a local library to definitions, resolving option defaults the way
 * core does: the class falls back to the option ID, and the attribute to the
 * style's attribute, then `class`.
 */
export function definitionsFromStyleLibrary(
  library: StyleLibraryPayload,
): StyleDefinitionSummary[] {
  return Object.entries(library.styles).map(([id, style]) => {
    const styleAttribute =
      typeof style.attribute === 'string' ? style.attribute : 'class';
    const options =
      style.options && typeof style.options === 'object'
        ? (style.options as Record<string, Record<string, unknown> | null>)
        : {};
    return {
      id,
      label: typeof style.label === 'string' ? style.label : id,
      providerType: 'site' as const,
      options: Object.entries(options).map(([optionId, option]) => ({
        id: optionId,
        label:
          typeof option?.label === 'string' ? option.label : String(optionId),
        value:
          option?.value === undefined || option?.value === null
            ? optionId
            : String(option.value),
        attribute:
          typeof option?.attribute === 'string'
            ? option.attribute
            : styleAttribute,
      })),
      tokens: normalizeStyleTokens(style.tokens),
      custom: normalizeStyleCustom(style.custom),
    };
  });
}

/**
 * Merges definitions by style ID. Earlier lists win, so pass local libraries
 * first to prefer local edits over the snapshot.
 */
export function mergeStyleDefinitions(
  ...lists: StyleDefinitionSummary[][]
): StyleDefinitionSummary[] {
  const merged = new Map<string, StyleDefinitionSummary>();
  for (const list of lists) {
    for (const definition of list) {
      if (!merged.has(definition.id)) {
        merged.set(definition.id, definition);
      }
    }
  }
  return [...merged.values()];
}

/** Whether a code component can receive every option as className/style. */
export function onlySetsClassOrStyle(
  definition: StyleDefinitionSummary,
): boolean {
  return definition.options.every((option) =>
    CODE_COMPONENT_ATTRIBUTES.includes(option.attribute),
  );
}

/** Resolves which known definitions a component accepts. */
export function acceptedStyleDefinitions(
  accepted: AcceptedStyles,
  definitions: StyleDefinitionSummary[],
): StyleDefinitionSummary[] {
  if (accepted === '*') {
    return definitions.filter(onlySetsClassOrStyle);
  }
  if (!Array.isArray(accepted)) {
    return [];
  }
  const byId = new Map(definitions.map((d) => [d.id, d]));
  return accepted
    .map((id) => byId.get(id))
    .filter((definition): definition is StyleDefinitionSummary =>
      Boolean(definition),
    );
}

/**
 * Every class an option, a brand kit color, or a custom value adds, split on
 * whitespace, deduplicated, sorted.
 */
export function collectOptionClasses(
  definitions: StyleDefinitionSummary[],
): string[] {
  const classes = new Set<string>();
  const add = (value: string) => {
    for (const name of value.split(/\s+/)) {
      if (name) {
        classes.add(name);
      }
    }
  };
  for (const definition of definitions) {
    for (const option of definition.options) {
      if (option.attribute === 'class') {
        add(option.value);
      }
    }
    if (typeof definition.tokens?.value === 'string') {
      add(definition.tokens.value);
    }
    if (typeof definition.custom?.value === 'string') {
      add(definition.custom.value);
    }
  }
  return [...classes].sort();
}

/**
 * The value types a style accepts: its option IDs, brand kit color
 * references, and custom values such as `=24px`.
 */
function styleValueUnion(definition: StyleDefinitionSummary): string {
  const members = definition.options
    .filter((option) => !(definition.tokens && option.kind === 'token'))
    .map((option) => JSON.stringify(option.id));
  if (definition.tokens) {
    const type = /^[a-z]+$/.test(definition.tokens.type ?? '')
      ? definition.tokens.type
      : 'color';
    members.push(`\`canvas-${type}:\${string}\``);
  }
  const units = definition.custom?.units;
  if (Array.isArray(units) && units.length > 0) {
    const named = units.filter((unit) => unit !== '');
    if (units.includes('')) {
      members.push('`=${number}`');
    }
    if (named.length > 0) {
      members.push(
        `\`=\${number}\${${named.map((unit) => JSON.stringify(unit)).join(' | ')}}\``,
      );
    }
  }
  return members.length > 0 ? members.join(' | ') : 'never';
}

function propertyKey(name: string): string {
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name) ? name : JSON.stringify(name);
}

/** A component's accepted styles, for generated outputs. */
export interface ComponentStyleDeclaration {
  machineName: string;
  styles: AcceptedStyles;
  styleParts?: StyleParts;
}

/**
 * Generates `CanvasStyleRegistry` augmentation. Every component is listed,
 * with an empty map when it accepts no known styles, so
 * `useStyleOptions<'name'>()` resolves for every local component. Part
 * styles are keyed `part.style_id`, like their selection keys.
 */
export function generateStylesDts(
  components: ComponentStyleDeclaration[],
  definitions: StyleDefinitionSummary[],
): string {
  const entries = [...components]
    .sort((a, b) => a.machineName.localeCompare(b.machineName))
    .map(({ machineName, styles, styleParts }) => {
      const member = (key: string, definition: StyleDefinitionSummary) =>
        `${propertyKey(key)}?: ${styleValueUnion(definition)};`;
      const members = [
        ...acceptedStyleDefinitions(styles, definitions).map((definition) =>
          member(definition.id, definition),
        ),
        ...Object.entries(styleParts ?? {}).flatMap(([partId, part]) =>
          acceptedStyleDefinitions(partStyleIds(part), definitions).map(
            (definition) => member(`${partId}.${definition.id}`, definition),
          ),
        ),
      ];
      return members.length > 0
        ? `    ${propertyKey(machineName)}: {\n${members.map((m) => `      ${m}`).join('\n')}\n    };`
        : `    ${propertyKey(machineName)}: {};`;
    });
  return [
    `// ${GENERATED_HEADER}`,
    // The export makes this file a module, so the declaration below augments
    // `drupal-canvas` instead of replacing its types.
    'export {};',
    '',
    "declare module 'drupal-canvas' {",
    '  interface CanvasStyleRegistry {',
    ...entries,
    '  }',
    '}',
    '',
  ].join('\n');
}

/** Generates the Tailwind `@source inline()` file for option classes. */
export function generateStylesCss(
  definitions: StyleDefinitionSummary[],
): string {
  const classes = collectOptionClasses(definitions);
  const lines = [`/* ${GENERATED_HEADER} */`];
  if (classes.length > 0) {
    lines.push(`@source inline(${JSON.stringify(classes.join(' '))});`);
  }
  return `${lines.join('\n')}\n`;
}

/** Reads `.canvas/styles.json`, or an empty list when it is missing. */
export async function readStylesSnapshot(
  projectRoot: string,
): Promise<StyleDefinitionSummary[]> {
  try {
    const raw = await fs.readFile(
      path.join(projectRoot, CANVAS_OUTPUT_DIR, STYLES_SNAPSHOT_FILENAME),
      'utf-8',
    );
    const parsed = JSON.parse(raw) as unknown;
    return Array.isArray(parsed)
      ? (parsed as StyleDefinitionSummary[]).filter(
          (definition) =>
            typeof definition?.id === 'string' &&
            Array.isArray(definition.options),
        )
      : [];
  } catch {
    return [];
  }
}

/** Writes `.canvas/styles.json`, `styles.d.ts`, and `styles.css`. */
export async function writeCanvasStyleOutputs(
  projectRoot: string,
  snapshot: StyleDefinition[],
  components: ComponentStyleDeclaration[],
): Promise<string[]> {
  const outputDir = path.join(projectRoot, CANVAS_OUTPUT_DIR);
  await fs.mkdir(outputDir, { recursive: true });
  const files: Record<string, string> = {
    [STYLES_SNAPSHOT_FILENAME]: `${JSON.stringify(snapshot, null, 2)}\n`,
    'styles.d.ts': generateStylesDts(components, snapshot),
    'styles.css': generateStylesCss(snapshot),
  };
  await Promise.all(
    Object.entries(files).map(([name, contents]) =>
      fs.writeFile(path.join(outputDir, name), contents, 'utf-8'),
    ),
  );
  return Object.keys(files).map((name) => path.join(CANVAS_OUTPUT_DIR, name));
}
