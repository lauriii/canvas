/**
 * @file
 * Build-time generation of the component implementation registry and the
 * brand kit stylesheet consumed by framework adapters. Node-only: discovery
 * reads the app filesystem.
 */

import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import {
  BRAND_KIT_CONFIG_FILENAME,
  buildBrandKitCss,
  discoverCanvasProject,
  loadComponentsMetadata,
  resolveCanvasConfig,
} from '@drupal-canvas/discovery';

import { COMPONENT_ENTRY_EXTENSIONS } from './component-entry-extensions';

export interface ComponentRegistryOptions {
  /** The app directory containing canvas.config.json. Default: process.cwd(). */
  projectRoot?: string;
  /**
   * Filesystem path of the generated module. When present, entry imports are
   * relative to this file; otherwise absolute imports are generated for a
   * framework virtual module.
   */
  modulePath?: string;
}

export interface ComponentRegistrySourcePaths {
  /** The app's Canvas configuration file. */
  configPath: string;
  /** The component discovery root selected by the current configuration. */
  componentRoot: string;
  /** The app's configured global CSS entrypoint. */
  globalCssPath: string;
  /** The app's canvas.brand-kit.json, which may not exist. */
  brandKitPath: string;
}

/**
 * Where adapters write the generated brand kit stylesheet, relative to the
 * app root. A real file, so each bundler resolves, serves, and hot-updates it
 * like any other stylesheet; keep `.canvas/` out of version control.
 */
export const BRAND_KIT_STYLESHEET_PATH = '.canvas/brand-kit.css';

export interface BrandKitStylesheetOptions {
  /** The app directory containing canvas.brand-kit.json. Default: process.cwd(). */
  projectRoot?: string;
  /**
   * Filesystem path of the generated stylesheet. Local font URLs are relative
   * to this file, so the app's bundler resolves and emits the font files.
   */
  stylesheetPath: string;
  /** Reports a provider font family that could not be resolved. */
  onFontError?: (family: string, error: unknown) => void;
}

/**
 * Generates a module with one static default import per discovered component.
 *
 * Static imports let each framework bundler trace the implementations while
 * component discovery keeps the registry synchronized with component.yml.
 * Duplicate machine names follow the Drupal reader's policy: the first wins.
 */
export async function buildComponentRegistryModule(
  options: ComponentRegistryOptions = {},
): Promise<string> {
  const projectRoot = path.resolve(options.projectRoot ?? process.cwd());
  const config = resolveCanvasConfig({ hostRoot: projectRoot });
  const result = await discoverCanvasProject({
    componentRoot: path.resolve(projectRoot, config.componentDir),
    pagesRoot: path.resolve(projectRoot, config.pagesDir),
    projectRoot,
    entryExtensions: COMPONENT_ENTRY_EXTENSIONS,
  });
  const metadata = await loadComponentsMetadata(result);
  const seenMachineNames = new Set<string>();
  const entries = metadata.flatMap((component, index) => {
    const discovered = result.components[index];
    if (
      !discovered?.jsEntryPath ||
      seenMachineNames.has(component.machineName)
    ) {
      return [];
    }
    seenMachineNames.add(component.machineName);
    return [
      {
        machineName: component.machineName,
        importPath: getImportPath(discovered.jsEntryPath, options.modulePath),
      },
    ];
  });

  const imports = entries.map(
    ({ importPath }, index) =>
      `import Component${index} from ${JSON.stringify(importPath)};`,
  );
  const registry = entries.map(
    ({ machineName }, index) =>
      `  ${JSON.stringify(machineName)}: Component${index},`,
  );

  return [
    '/** Generated by the Drupal Canvas Headless SDK. */',
    ...imports,
    '',
    'const components = {',
    ...registry,
    '};',
    '',
    'export default components;',
    '',
  ].join('\n');
}

/**
 * Generates the brand kit stylesheet from canvas.brand-kit.json: the
 * `@font-face` rules and color custom properties Drupal generates for the
 * site's brand kit, fonts first. Import it next to the app's global CSS.
 *
 * Local font files are referenced relative to `stylesheetPath`. Provider
 * font families resolve over the network, as `canvas push` does; one that
 * cannot be resolved is skipped and reported through `onFontError`. A
 * missing or malformed brand kit file yields an empty stylesheet.
 */
export async function buildBrandKitStylesheet(
  options: BrandKitStylesheetOptions,
): Promise<string> {
  const projectRoot = path.resolve(options.projectRoot ?? process.cwd());
  const css = await buildBrandKitCss(projectRoot, {
    localFontUrl: (face) => getImportPath(face.path, options.stylesheetPath),
    onFontError: options.onFontError,
  });
  return css === ''
    ? ''
    : `/* Generated by the Drupal Canvas Headless SDK. */\n${css}\n`;
}

/**
 * Writes the generated brand kit stylesheet to `stylesheetPath`, only when its
 * content changed so file watchers do not see spurious updates. It is written
 * even when empty, so the app's import always resolves.
 */
export async function writeBrandKitStylesheet(
  options: BrandKitStylesheetOptions,
): Promise<void> {
  const css = await buildBrandKitStylesheet(options);
  const current = await readFile(options.stylesheetPath, 'utf8').catch(
    () => null,
  );
  if (current !== css) {
    await mkdir(path.dirname(options.stylesheetPath), { recursive: true });
    await writeFile(options.stylesheetPath, css);
  }
}

/** Resolves the configured source locations used to build the registry. */
export function resolveComponentRegistrySourcePaths(
  options: Pick<ComponentRegistryOptions, 'projectRoot'> = {},
): ComponentRegistrySourcePaths {
  const projectRoot = path.resolve(options.projectRoot ?? process.cwd());
  const config = resolveCanvasConfig({ hostRoot: projectRoot });
  return {
    configPath: path.join(projectRoot, 'canvas.config.json'),
    componentRoot: path.resolve(projectRoot, config.componentDir),
    globalCssPath: path.resolve(projectRoot, config.globalCssPath),
    brandKitPath: path.join(projectRoot, BRAND_KIT_CONFIG_FILENAME),
  };
}

function getImportPath(entryPath: string, modulePath?: string): string {
  if (!modulePath) {
    return normalizePath(entryPath);
  }
  const relativePath = normalizePath(
    path.relative(path.dirname(modulePath), entryPath),
  );
  return relativePath.startsWith('.') ? relativePath : `./${relativePath}`;
}

function normalizePath(filePath: string): string {
  return filePath.split(path.sep).join('/');
}
